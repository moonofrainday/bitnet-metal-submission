#!/usr/bin/env python3
"""Prepare actual phone W/X for original-PoC qualification; no GPU runs."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil

MODEL='52257df879ab4366d97228e7bda94a9a3c6a9065ec44e7879a8b87d54e568cd2'


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--real-fixture',type=Path,required=True,help='Accepted real Q fixture with steps 1/16/32')
    p.add_argument('--output',type=Path,required=True,help='New local directory; raw payloads never go in Git')
    a=p.parse_args();source=a.real_fixture.expanduser().resolve();output=a.output.expanduser().resolve()
    if output.exists():p.error('Refusing existing output')
    manifest=json.loads((source/'MANIFEST.json').read_text())
    if manifest.get('model_sha256')!=MODEL:p.error('Public model identity differs')
    records=[]
    for step in (1,16,32):
        folder=source/('step-'+str(step));bound=manifest['fixtures'][str(step)]
        for name,n in [('w.tq2',1689600),('x.f32',10240)]:
            f=folder/name
            if f.stat().st_size!=n or sha(f)!=bound[name]['sha256']:p.error('Actual fixture identity/extent differs: '+str(f))
        records.append({'id':'real-step-'+str(step),'step':step,
            'weights':'real-step-'+str(step)+'/w.tq2','activation':'real-step-'+str(step)+'/x.f32',
            'weights_sha256':sha(folder/'w.tq2'),'activation_sha256':sha(folder/'x.f32')})
    output.mkdir(parents=True)
    for record in records:
        folder=output/record['id'];folder.mkdir()
        step=record['step']
        for name in ('w.tq2','x.f32'):shutil.copy2(source/('step-'+str(step))/name,folder/name)
    doc={'schema':1,'model_sha256':MODEL,'cases':records,
         'synthetic_cases':'known-answer and dense-seed42 generated by unchanged validation/reference.cpp on the phone',
         'source_fixture_manifest_sha256':sha(source/'MANIFEST.json'),
         'source_capture_acceptance_sha256':manifest.get('acceptance_sha256'),
         'libraries':{},'embedded_framework_sha256':None,
         'tolerance':{'abs':2e-4,'relative':2e-5},
         'scope':'Five 2560x2560 N1 cases; independent original 4x2 PoC vs actual S and Q4; no graph/model-semantic acceptance',
         'raw_artifacts_stay_local':True}
    (output/'MANIFEST.json').write_text(json.dumps(doc,indent=2)+'\n')
    print('Prepared three hash-bound real inputs; known/dense cases are generated natively. No GPU work run.')
    return 0


if __name__=='__main__':raise SystemExit(main())
